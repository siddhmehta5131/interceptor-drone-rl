"""Traversal and validation of the sourced-configuration schema (plan P2.1).

A sourced leaf is a mapping with ``value`` and ``unit`` and a non-empty
``source`` string.  Descriptive top-level keys (``description``, ``notes``,
``primary_source``, ``license``, ...) are metadata and are skipped.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Iterator, List, Mapping, Sequence

import yaml

__all__ = [
    "SOURCE_FILES", "METADATA_KEYS", "SourceLeaf", "load_yaml",
    "iter_source_leaves", "unsourced_leaves", "render_source_table",
]

SOURCE_FILES = (
    "configs/quadrotor.yaml",
    "configs/fc.yaml",
    "configs/platforms.yaml",
    "configs/guidance.yaml",
    "configs/seeker.yaml",
    "configs/maneuvers.yaml",
    "configs/airframes/aerosonde.yaml",
    "configs/airframes/aim5.yaml",
)

METADATA_KEYS = {
    "description", "notes", "source", "license", "licence", "primary_source",
    "airframe", "model", "schema", "title", "references", "unit", "units",
}


@dataclass(frozen=True)
class SourceLeaf:
    path: str
    value: object
    unit: object
    source: object

    @property
    def is_sourced(self) -> bool:
        source = "" if self.source is None else str(self.source)
        return bool(source.strip()) and "TODO" not in source.upper()

    @property
    def value_text(self) -> str:
        if isinstance(self.value, (list, tuple, dict)):
            return json.dumps(self.value, separators=(", ", ": "))
        return str(self.value)


def load_yaml(path: "str | Path") -> dict:
    with Path(path).open("r", encoding="utf-8") as handle:
        return yaml.safe_load(handle) or {}


def iter_source_leaves(node, prefix: Sequence[str] = ()) -> Iterator[SourceLeaf]:
    """Yield every sourced leaf beneath ``node``."""
    if isinstance(node, Mapping):
        if "value" in node:
            yield SourceLeaf(
                path=".".join(prefix),
                value=node.get("value"),
                unit=node.get("unit"),
                source=node.get("source"),
            )
            return
        for key, child in node.items():
            if str(key) in METADATA_KEYS:
                continue
            yield from iter_source_leaves(child, (*prefix, str(key)))
    elif isinstance(node, (list, tuple)):
        for index, child in enumerate(node):
            yield from iter_source_leaves(child, (*prefix, f"[{index}]"))


def unsourced_leaves(node) -> List[SourceLeaf]:
    """Return leaves missing a source or carrying a TODO marker."""
    return [leaf for leaf in iter_source_leaves(node) if not leaf.is_sourced]


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_source_table(root: "str | Path" = ".", files: Iterable[str] = SOURCE_FILES) -> str:
    """Render ``docs/source_table.md`` from the sourced configuration files."""
    root = Path(root)
    lines = [
        "# Source table",
        "",
        "Generated by `scripts/build_source_table.py` from the `{value, unit, source}`",
        "config files.  Regenerate after changing a sourced value; the",
        "`test_all_constants_sourced` test fails on any missing source or `TODO`.",
        "",
        "## Licences",
        "",
        "- `mavsim_public`: GPL-3.0 (confirmed in the repository `LICENSE`).  Only",
        "  numerical Aerosonde data is used, with citation; no source code is copied.",
        "- CADAC (`SwaggyTyrion/CADAC`): MIT, added by the repository owner.  The",
        "  AIM5 decks originate from Zipfel's book supplement; only numerical data",
        "  is used, with citation; no source code is copied.",
        "- Crazyflie/NanoBench values are cited facts from the papers and Bitcraze",
        "  datasheets; the derived PID gains are this project's own work.",
        "",
        "## Values",
        "",
        "| File | Path | Value | Unit | Source |",
        "|---|---|---|---|---|",
    ]
    count = 0
    for name in files:
        data = load_yaml(root / name)
        for leaf in iter_source_leaves(data):
            count += 1
            lines.append(
                f"| `{_cell(name)}` | `{_cell(leaf.path)}` | "
                f"`{_cell(leaf.value_text)}` | {_cell(leaf.unit)} | "
                f"{_cell(leaf.source)} |"
            )
    lines += ["", f"**{count} sourced leaves; 0 TODO.**", ""]
    return "\n".join(lines)
